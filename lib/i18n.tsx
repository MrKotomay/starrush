const dictionaries = { ru, en }

type TranslationKey = keyof typeof ru

function localeToIntl(locale: AppLocale) {
  return locale === "ru" ? "ru-RU" : "en-US"
}

function interpolate(template: string, vars?: TranslationVars) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

export function useI18n() {
  const { locale } = useAppSettings()

  const t = useCallback(
    (key: TranslationKey | string, vars?: TranslationVars) => {
      const dictionary = dictionaries[locale] as Record<string, string>
      const fallbackDictionary = dictionaries.ru as Record<string, string>
      const template = dictionary[key] ?? fallbackDictionary[key] ?? key
      return interpolate(template, vars)
    },
    [locale],
  )

  const intlLocale = useMemo(() => localeToIntl(locale), [locale])

  const formatNumber = useCallback(
    (value: number, options?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(intlLocale, options).format(value),
    [intlLocale],
  )

  const formatDate = useCallback(
    (value: number | string | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(intlLocale, options ?? { year: "numeric", month: "2-digit", day: "2-digit" }).format(
        typeof value === "number" || typeof value === "string" ? new Date(value) : value,
      ),
    [intlLocale],
  )

  const formatTime = useCallback(
    (value: number | string | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(intlLocale, options ?? { hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false }).format(
        typeof value === "number" || typeof value === "string" ? new Date(value) : value,
      ),
    [intlLocale],
  )

  const formatDateTime = useCallback(
    (value: number | string | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(intlLocale, options ?? {
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
      }).format(typeof value === "number" || typeof value === "string" ? new Date(value) : value),
    [intlLocale],
  )

  return {
    locale,
    intlLocale,
    t,
    formatNumber,
    formatDate,
    formatTime,
    formatDateTime,
  }
}
